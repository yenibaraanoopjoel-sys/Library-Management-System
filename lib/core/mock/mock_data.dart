/// Notification model for user alerts
class AppNotification {
  final String id;
  final String userId;
  final String title;
  final String message;
  final String type; // 'due_soon', 'overdue', 'fine_assessed', 'general', 'return'
  final DateTime timestamp;
  bool isRead;

  AppNotification({
    required this.id,
    required this.userId,
    required this.title,
    required this.message,
    required this.type,
    required this.timestamp,
    this.isRead = false,
  });
}

